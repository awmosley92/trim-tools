/* Digital Scribe — service worker.
   Cache-first so the tools open instantly with no signal; every successful
   fetch refreshes the cache in the background, so the next open is current.
   Bump VERSION whenever you change a tool and want phones to pick it up. */

const VERSION = 'ds-2026-11-18-a';
const CACHE = `digital-scribe-${VERSION}`;

const ASSETS = [
  './',
  './index.html',
  './stool.html',
  './reveal.html',
  './manifest.webmanifest',
  './icons/icon-180.png',
  './icons/icon-192.png',
  './icons/icon-512.png',
  './icons/icon-512-maskable.png'
];

self.addEventListener('install', event => {
  event.waitUntil(
    caches.open(CACHE)
      // one bad path must not fail the whole install
      .then(c => Promise.allSettled(ASSETS.map(a => c.add(a))))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', event => {
  event.waitUntil(
    caches.keys()
      .then(keys => Promise.all(
        keys.filter(k => k.startsWith('digital-scribe-') && k !== CACHE)
            .map(k => caches.delete(k))
      ))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', event => {
  const req = event.request;
  if (req.method !== 'GET') return;

  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;

  event.respondWith(
    caches.match(req).then(hit => {
      const live = fetch(req).then(res => {
        if (res && res.ok) {
          const copy = res.clone();
          caches.open(CACHE).then(c => c.put(req, copy)).catch(() => {});
        }
        return res;
      }).catch(() => hit);

      // serve the cached copy immediately; refresh behind it
      return hit || live;
    })
  );
});
